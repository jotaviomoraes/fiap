# ---------------------------------------------------------------------
# Traducao SQLite -> Oracle
# ---------------------------------------------------------------------
def _mascarar_literais(sql: str) -> tuple[str, list[str]]:
    """Troca o conteudo de literais por marcadores para analisar a estrutura."""
    literais: list[str] = []

    def troca(m):
        literais.append(m.group(0))
        return f"__LIT{len(literais) - 1}__"

    return re.sub(r"'(?:''|[^'])*'", troca, sql), literais


def _desmascarar(sql: str, literais: list[str]) -> str:
    for i, valor in enumerate(literais):
        sql = sql.replace(f"__LIT{i}__", valor)
    return sql


def _fechar_parentese(texto: str, inicio: int) -> int:
    profundidade = 0
    for i in range(inicio, len(texto)):
        if texto[i] == "(":
            profundidade += 1
        elif texto[i] == ")":
            profundidade -= 1
            if profundidade == 0:
                return i
    return -1


def _converter_sums(sql: str) -> str:
    """Converte SUM(condicao_booleana) em SUM(CASE WHEN condicao THEN 1 ELSE 0 END)."""
    resultado = sql
    pos = 0
    while True:
        m = re.search(r"\bSUM\s*\(", resultado[pos:], re.IGNORECASE)
        if not m:
            return resultado
        inicio = pos + m.start()
        abre = resultado.find("(", inicio)
        fecha = _fechar_parentese(resultado, abre)
        if fecha == -1:
            return resultado
        interno = resultado[abre + 1:fecha]
        sem_literal, _ = _mascarar_literais(interno)
        booleano = (
            not sem_literal.strip().upper().startswith("CASE")
            and re.search(r"(=|<>|!=|\bIS\s+(?:NOT\s+)?NULL\b|\bAND\b|\bOR\b)", sem_literal, re.IGNORECASE)
        )
        if booleano:
            novo = f"SUM(CASE WHEN {interno} THEN 1 ELSE 0 END)"
            resultado = resultado[:inicio] + novo + resultado[fecha + 1:]
            pos = inicio + len(novo)
        else:
            pos = fecha + 1


def _lista_select(sql: str) -> tuple[str, str, str] | None:
    """Separa SELECT / lista de colunas / resto, no nivel superior."""
    m = re.match(r"\s*SELECT\s+(.*?)\s+FROM\s+(.*)$", sql, re.IGNORECASE | re.DOTALL)
    if not m:
        return None
    return "SELECT", m.group(1), "FROM " + m.group(2)


def _dividir_topo(texto: str, separador: str = ",") -> list[str]:
    partes, atual, profundidade = [], [], 0
    for ch in texto:
        if ch == "(":
            profundidade += 1
        elif ch == ")":
            profundidade -= 1
        if ch == separador and profundidade == 0:
            partes.append("".join(atual))
            atual = []
        else:
            atual.append(ch)
    partes.append("".join(atual))
    return partes


def _mapa_aliases(sql: str) -> dict[str, str]:
    info = _lista_select(sql)
    if not info:
        return {}
    mapa = {}
    for item in _dividir_topo(info[1]):
        m = re.match(r"\s*(.*?)\s+AS\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", item, re.IGNORECASE | re.DOTALL)
        if m:
            mapa[m.group(2).lower()] = m.group(1).strip()
    return mapa


def _resolver_group_by(sql: str) -> str:
    """Oracle nao aceita alias de SELECT no GROUP BY: substitui pela expressao."""
    aliases = _mapa_aliases(sql)
    info = _lista_select(sql)
    primeira = _dividir_topo(info[1])[0].strip() if info else ""

    def troca(m):
        itens = _dividir_topo(m.group(1))
        novos = []
        for item in itens:
            token = item.strip()
            if token == "1" and primeira:
                novos.append(primeira)
            elif token.lower() in aliases and "." not in token:
                novos.append(aliases[token.lower()])
            else:
                novos.append(token)
        return "GROUP BY " + ", ".join(novos)

    return re.sub(r"\bGROUP\s+BY\s+([^)]*?)(?=\s+ORDER\s+BY\b|\s+HAVING\b|\s*$)",
                  troca, sql, flags=re.IGNORECASE | re.DOTALL)


def traduzir_sql(sql: str) -> str:
    """Converte o SQL portavel usado em `relatorios.py` para o dialeto Oracle."""
    sql = re.sub(
        r"\bstrftime\s*\(\s*'%H'\s*,\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\)",
        r"TO_NUMBER(TO_CHAR(TO_DATE(\1, 'YYYY-MM-DD HH24:MI:SS'), 'HH24'))",
        sql, flags=re.IGNORECASE,
    )
    sql = re.sub(r"\bdate\s*\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\)",
                 r"SUBSTR(\1, 1, 10)", sql, flags=re.IGNORECASE)
    sql = _converter_sums(sql)
    sql = _resolver_group_by(sql)
    # marcadores posicionais do SQLite -> binds posicionais do oracledb
    partes = sql.split("?")
    if len(partes) > 1:
        sql = "".join(f"{parte}:{i}" for i, parte in enumerate(partes[:-1])) + partes[-1]
    return sql


def _preparar(sql: str, params: tuple | list) -> tuple[str, list]:
    params = list(params)
    m = re.search(r"\bLIMIT\s+\?\s*$", sql, re.IGNORECASE)
    if m:
        limite = int(params.pop() or 1)
        sql = sql[:m.start()] + f"FETCH FIRST {limite} ROWS ONLY"
    else:
        sql = re.sub(r"\bLIMIT\s+(\d+)\s*$", lambda m: f"FETCH FIRST {m.group(1)} ROWS ONLY",
                     sql, flags=re.IGNORECASE)
    return traduzir_sql(sql), params


