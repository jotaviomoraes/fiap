    def contar(self, tabela: str) -> int:
        if not re.fullmatch(r"[a-z_]+", tabela):
            raise ValueError("Nome de tabela invalido")
        return int(self.consultar(f"SELECT COUNT(*) AS total FROM {tabela}").iloc[0]["total"])
