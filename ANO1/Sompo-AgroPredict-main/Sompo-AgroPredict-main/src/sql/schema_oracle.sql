-- =====================================================================
-- AgroPredict — schema do Oracle Autonomous Database (modo Thin)
-- ---------------------------------------------------------------------
-- Este arquivo documenta o schema criado automaticamente pelo sistema.
-- Para aplicar de forma idempotente e não destrutiva, use:
--
--     python scripts/criar_schema_oracle.py
--
-- O repositório (`src/agropredict/repositorio_oracle.py`) cria apenas o
-- que ainda não existe e nunca remove dados. Se você executar este .sql
-- manualmente em um schema já populado, os CREATE TABLE podem retornar
-- ORA-00955 (objeto já existe) — isso é esperado e não deve ser
-- "corrigido" com DROP.
-- =====================================================================

CREATE TABLE equipamentos (
    id_equipamento NUMBER(10) PRIMARY KEY,
    codigo         VARCHAR2(20)  NOT NULL UNIQUE,
    tipo           VARCHAR2(30)  NOT NULL,
    modelo         VARCHAR2(60)  NOT NULL,
    fabricante     VARCHAR2(60)  NOT NULL,
    ano_fabricacao NUMBER(4)     NOT NULL,
    fazenda        VARCHAR2(100) NOT NULL,
    regiao         VARCHAR2(100) NOT NULL,
    ativo          NUMBER(1) DEFAULT 1 NOT NULL CHECK (ativo IN (0, 1))
);

CREATE TABLE usuarios (
    id_usuario NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    usuario    VARCHAR2(120) NOT NULL UNIQUE,
    nome       VARCHAR2(200),
    perfil     VARCHAR2(20)  NOT NULL
               CHECK (perfil IN ('operador', 'gestor', 'tecnico', 'analista', 'admin')),
    senha_hash VARCHAR2(300) NOT NULL,
    ativo      NUMBER(1) DEFAULT 1 NOT NULL CHECK (ativo IN (0, 1)),
    criado_em  VARCHAR2(19) NOT NULL
);

CREATE TABLE leituras (
    id_leitura            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    data_hora             VARCHAR2(19)  NOT NULL,
    id_equipamento        NUMBER(10)    NOT NULL REFERENCES equipamentos (id_equipamento),
    usuario               VARCHAR2(120) NOT NULL,
    origem                VARCHAR2(30)  NOT NULL,
    umidade_solo          NUMBER(8,2)   NOT NULL,
    declividade           NUMBER(8,2)   NOT NULL,
    chuva_24h             NUMBER(8,2)   NOT NULL,
    temperatura           NUMBER(8,2)   NOT NULL,
    velocidade            NUMBER(8,2)   NOT NULL,
    idade_maquina         NUMBER(8,2)   NOT NULL,
    horas_operacao        NUMBER(8,2)   NOT NULL,
    status_operacao       VARCHAR2(20)  NOT NULL
                          CHECK (status_operacao IN ('Colheita', 'Deslocamento', 'Manobra')),
    fonte_umidade         VARCHAR2(30),
    fonte_clima           VARCHAR2(30),
    fonte_velocidade      VARCHAR2(30),
    fonte_horas           VARCHAR2(30),
    fonte_idade           VARCHAR2(30),
    latitude              NUMBER(12,7),
    longitude             NUMBER(12,7),
    status_processamento  VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL
                          CHECK (status_processamento IN ('PENDENTE', 'PROCESSADA', 'ERRO')),
    erro_processamento    VARCHAR2(500),
    hash_entrada          VARCHAR2(64)
);

CREATE TABLE predicoes (
    id_predicao       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_leitura        NUMBER(19) NOT NULL UNIQUE REFERENCES leituras (id_leitura),
    data_hora         VARCHAR2(19) NOT NULL,
    classe_modelo     VARCHAR2(10) NOT NULL CHECK (classe_modelo IN ('BAIXO', 'MEDIO', 'ALTO')),
    classe_risco      VARCHAR2(10) NOT NULL CHECK (classe_risco IN ('BAIXO', 'MEDIO', 'ALTO')),
    score_risco       NUMBER(6,2)  NOT NULL CHECK (score_risco BETWEEN 0 AND 100),
    prob_baixo        NUMBER(10,8) NOT NULL,
    prob_medio        NUMBER(10,8) NOT NULL,
    prob_alto         NUMBER(10,8) NOT NULL,
    override_aplicado NUMBER(1)    NOT NULL CHECK (override_aplicado IN (0, 1)),
    motivo_override   VARCHAR2(500),
    variaveis_alerta  VARCHAR2(500),
    explicacao        CLOB,
    recomendacao      VARCHAR2(500) NOT NULL,
    versao_modelo     VARCHAR2(50) NOT NULL,
    hash_modelo       VARCHAR2(64) NOT NULL,
    gravado_oracle    NUMBER(1) DEFAULT 0 NOT NULL CHECK (gravado_oracle IN (0, 1))
);

CREATE TABLE alertas (
    id_alerta    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_predicao  NUMBER(19) NOT NULL UNIQUE REFERENCES predicoes (id_predicao),
    data_emissao VARCHAR2(19) NOT NULL,
    nivel        VARCHAR2(10) NOT NULL CHECK (nivel IN ('MEDIO', 'ALTO')),
    categoria    VARCHAR2(20) NOT NULL CHECK (categoria IN ('operacional', 'climatico', 'mecanico')),
    mensagem     VARCHAR2(500) NOT NULL,
    acao_tomada  VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL
                 CHECK (acao_tomada IN ('PENDENTE', 'RESPEITOU', 'IGNOROU')),
    data_acao    VARCHAR2(19),
    usuario_acao VARCHAR2(120),
    observacao   VARCHAR2(500)
);

CREATE TABLE log_acessos (
    id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    data_hora VARCHAR2(19)  NOT NULL,
    usuario   VARCHAR2(120) NOT NULL,
    perfil    VARCHAR2(20),
    evento    VARCHAR2(60)  NOT NULL,
    sucesso   NUMBER(1) NOT NULL CHECK (sucesso IN (0, 1))
);

CREATE TABLE rejeicoes (
    id_rejeicao    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    data_hora      VARCHAR2(19)  NOT NULL,
    origem         VARCHAR2(30)  NOT NULL,
    usuario        VARCHAR2(120),
    id_equipamento NUMBER(10),
    tipo           VARCHAR2(20)  NOT NULL CHECK (tipo IN ('INVALIDA', 'DUPLICADA')),
    motivo         VARCHAR2(500) NOT NULL,
    dados          CLOB
);

CREATE TABLE configuracoes (
    chave         VARCHAR2(100) PRIMARY KEY,
    valor         VARCHAR2(4000),
    atualizado_em VARCHAR2(19) NOT NULL
);

CREATE INDEX idx_leituras_equip_data ON leituras (id_equipamento, data_hora);
CREATE INDEX idx_leituras_status ON leituras (status_processamento);
CREATE INDEX idx_leituras_hash ON leituras (hash_entrada);
CREATE INDEX idx_predicoes_classe ON predicoes (classe_risco);
CREATE INDEX idx_alertas_acao ON alertas (acao_tomada);
CREATE INDEX idx_log_usuario_data ON log_acessos (usuario, data_hora);
CREATE INDEX idx_rejeicoes_data ON rejeicoes (data_hora);

CREATE OR REPLACE VIEW vw_predicoes AS
SELECT
    p.id_predicao, l.id_leitura, l.data_hora, l.usuario, l.origem,
    e.id_equipamento, e.codigo AS equipamento, e.tipo AS tipo_equipamento,
    e.modelo, e.fabricante, e.fazenda, e.regiao,
    l.umidade_solo, l.declividade, l.chuva_24h, l.temperatura, l.velocidade,
    l.idade_maquina, l.horas_operacao, l.status_operacao,
    l.fonte_umidade, l.fonte_clima, l.fonte_velocidade, l.fonte_horas, l.fonte_idade,
    l.hash_entrada,
    p.classe_modelo, p.classe_risco, p.score_risco,
    p.prob_baixo, p.prob_medio, p.prob_alto,
    p.override_aplicado, p.motivo_override, p.variaveis_alerta, p.explicacao, p.recomendacao,
    p.versao_modelo, p.hash_modelo, p.gravado_oracle,
    a.id_alerta, a.nivel AS nivel_alerta, a.categoria AS categoria_alerta, a.acao_tomada
FROM predicoes p
JOIN leituras     l ON l.id_leitura     = p.id_leitura
JOIN equipamentos e ON e.id_equipamento = l.id_equipamento
LEFT JOIN alertas a ON a.id_predicao    = p.id_predicao;

